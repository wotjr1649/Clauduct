// betaNameShape bounds what may be recorded. The header is the client's own text and this
// record outlives the session, so an unexpected value must not be able to grow it.
var betaNameShape = regexp.MustCompile(`^[a-z][a-z0-9-]{0,63}$`)

// betaNames is how many distinct names of one kind are kept. The baseline's eight.
const betaNames = 8

// BetaReport is what the session saw asked for.
type BetaReport struct {
	// Requests is how many requests carried the header at all.
	Requests int64 `json:"requests"`
	// Malformed is how many of those had an empty or repeated item. Counted, never refused.
	Malformed int64 `json:"malformed,omitempty"`
	// Judged are the fixed labels for names this project decided are not implemented.
	Judged []string `json:"judged,omitempty"`
	// ServerDependent are names that need Anthropic's servers and are inert here.
	ServerDependent []string `json:"serverDependent,omitempty"`
	// Unknown are names nobody here has classified, bounded in shape and count.
	Unknown []string `json:"unknown,omitempty"`
}

// betaLedger accumulates what a session was asked for.
type betaLedger struct {
	mu              sync.Mutex
	requests        int64
	malformed       int64
	judged          map[string]bool
	serverDependent map[string]bool
	unknown         map[string]bool
}

func newBetaLedger() *betaLedger {
	return &betaLedger{
		judged:          map[string]bool{},
		serverDependent: map[string]bool{},
		unknown:         map[string]bool{},
	}
}

// observe classifies one request's header. An absent header is not an observation.
func (b *betaLedger) observe(header string) {
	if header == "" {
		return
	}
	names := strings.Split(header, ",")
	seen := make(map[string]bool, len(names))
	malformed := false

	b.mu.Lock()
	defer b.mu.Unlock()
	b.requests++

	for _, raw := range names {
		name := strings.TrimSpace(raw)
		if seen[name] {
			malformed = true
			continue
		}
		seen[name] = true
		switch {
		case nativeBetas[name]:
		case judgedBetas[name] != "":
			add(b.judged, judgedBetas[name])
		case serverDependentBetas[name]:
			add(b.serverDependent, name)
		case betaNameShape.MatchString(name):
			add(b.unknown, name)
		default:
			// An empty item, or text that is not a name at all. Counted and not written
			// down: there is nothing safe to record about it. Still not refused.
			malformed = true
		}
	}
	if malformed {
		b.malformed++
	}
}

// add keeps a bounded set. Past the bound a new name is dropped rather than evicting one,
// so what a reader sees is the first names the session met and not a window that slid.
func add(set map[string]bool, name string) {
	if len(set) >= betaNames && !set[name] {
		return
	}
	set[name] = true
}

func (b *betaLedger) report() BetaReport {
	b.mu.Lock()
	defer b.mu.Unlock()
	return BetaReport{
		Requests:        b.requests,
		Malformed:       b.malformed,
		Judged:          sorted(b.judged),
		ServerDependent: sorted(b.serverDependent),
		Unknown:         sorted(b.unknown),
	}
}

func sorted(set map[string]bool) []string {
	if len(set) == 0 {
		return nil
	}
	out := make([]string, 0, len(set))
	for name := range set {
		out = append(out, name)
	}
	sort.Strings(out)
	return out
}
