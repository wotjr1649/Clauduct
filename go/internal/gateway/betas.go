// What the client asked for that this bridge does not do.
//
// A beta name is never refused. That is measured, not chosen: the Node baseline records
// refusing one breaking WebFetch in a real session, because refusing a header fails the
// whole request while the feature it names is already inert against this backend.
//
// This build goes one step further and does not refuse a malformed header either, which is
// a deliberate departure from the baseline's INVALID_BETA_HEADER. The reasoning is the same
// one, applied to its own premise. The header reaches exactly one decision here, negotiated,
// which matches a trimmed name exactly -- so an empty item or a repeated one cannot change
// what is enabled. Refusing it would convert a client-side oddity with no effect into a dead
// turn, and this header is generated by the client, so the turn it kills is never the user's
// fault. It is counted instead, which tells a reader the same thing and costs nothing.
//
// What is kept is a fixed label, a bounded name or a count. The header is the client's own
// text, and this record is written to a file that outlives the session.

// nativeBetas are the names known to work through this bridge.
