// Audit the final executable's real TUI run using fixed identities and public markers.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url));
const base='D:/AIDEV/clauduct-s36-build/repair-20260919/verification/policy-repair-20260919';
const approved=path.join(base,'interactive-e268b95d-2048-47e3-b36b-5483000541a7');
const project=path.join(approved,'profile/projects/D--AIDEV-clauduct-s36-build-repair-20260919-verification-policy-repair-20260919-interactive-e268b95d-2048-47e3-b36b-5483000541a7-project');
const id='f55faaae-fef5-41c2-95fa-e6a8acbc1b76',run=path.join(base,'interactive-'+id);
const read=f=>{assert(fs.statSync(f).size<32*1024*1024);return fs.readFileSync(f,'utf8').replace(/^\uFEFF/,'');};
const json=f=>JSON.parse(read(f)),rows=f=>read(f).trim().split(/\r?\n/).map(JSON.parse);
const sha=f=>crypto.createHash('sha256').update(fs.readFileSync(f)).digest('hex');
const manifest=json(path.join(run,'run.json')),build=json(path.join(here,'build.json'));
assert.equal(build.commit,'3df87d369445796ba94da7880d0e4852247d3d90');
assert.equal(manifest.sha256,build.artifacts['clauduct.exe']);
assert.equal(path.resolve(manifest.profile),path.resolve(approved,'profile'));
assert.equal(manifest.state,'exited');assert.equal(manifest.exitCode,0);assert(!manifest.watchdogForced);
const files=fs.readdirSync(path.join(run,'tmp/clauduct')).filter(n=>/^status-\d+\.json$/.test(n));assert.equal(files.length,1);
const statusFile=path.join(run,'tmp/clauduct',files[0]),s=json(statusFile);
assert(s.lifecycle.final&&s.lifecycle.nativeReaped);assert.equal(s.gateway.requests.active,0);
for(const key of ['apiFailures','nativeToolFailures','unacquiredResultsInRecent','rejectedWorkflowCalls'])assert.equal(s.completion[key],0,key);
const blocks=r=>Array.isArray(r.message?.content)?r.message.content:typeof r.message?.content==='string'?[{type:'text',text:r.message.content}]:[];
const text=r=>blocks(r).filter(b=>b.type==='text').map(b=>b.text).join('\n');
const rootFile=path.join(project,id+'.jsonl'),root=rows(rootFile);
assert(root.some(r=>r.type==='assistant'&&text(r).trim()==='S44_FINAL_41'));
const selection=s.gateway.agentSelections.recent;assert.equal(selection.length,2);
assert(selection.every(c=>c.effectiveModel==='gpt-5.6-terra'&&c.effectiveEffort==='medium'&&c.state==='selection_verified'));
const middle=selection.find(c=>!c.parent),leaf=selection.find(c=>c.parent);assert.equal(leaf.parent,middle.agent);
assert(!leaf.modelProvided&&!leaf.effortProvided);assert.equal(leaf.source,'delegation-inherited');
const children=[middle,leaf].map(c=>{
 const f=path.join(project,id,'subagents','agent-'+c.agent+'.jsonl'),rr=rows(f);
 const markers=rr.filter(r=>r.type==='assistant').flatMap(r=>text(r).match(/S44_(?:LEAF|MIDDLE)_41/g)||[]);
 const tools=rr.flatMap(blocks).filter(b=>b.type==='tool_use').map(b=>b.name);
 assert(tools.every(n=>['Agent','ToolSearch','SendMessage'].includes(n)),'UNEXPECTED_TOOL');
 return {id:c.agent,parent:c.parent,model:c.effectiveModel,effort:c.effectiveEffort,source:c.source,sha256:sha(f),markers:[...new Set(markers)],tools};
});
assert(children[0].markers.includes('S44_MIDDLE_41'));assert(children[1].markers.includes('S44_LEAF_41'));assert.equal(children[1].tools.length,0);
const contexts=root.filter(r=>r.type==='user'&&text(r).startsWith('## Context Usage')).map(r=>({at:r.timestamp,tokens:text(r).match(/\*\*Tokens:\*\* ([^\n]+)/)?.[1],messages:text(r).split('\n').find(l=>/^\| Messages /.test(l))}));
assert.equal(contexts.length,2);assert(contexts[0].tokens);assert.equal(contexts[0].tokens,contexts[1].tokens);
const counts=s.gateway.modelContexts.reduce((a,m)=>({matched:a.matched+m.observed.countMatches,mismatched:a.mismatched+m.observed.countMismatches}),{matched:0,mismatched:0});assert.equal(counts.mismatched,0);
assert(s.gateway.contextDisplay.removedBlocks>0);
const report={id,commit:build.commit,binarySha256:manifest.sha256,native:s.gateway.client,statusSha256:sha(statusFile),transcriptSha256:sha(rootFile),completion:s.completion,lifecycle:s.lifecycle,counts,contexts,children,contextDisplay:s.gateway.contextDisplay,acceptance:{nestedInheritance:'pass',contextRepeat:'pass_observed_native_totals',allFormats:false,universal:false}};
fs.writeFileSync(path.join(here,'final-evidence.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify({id,counts,contexts,completion:s.completion}));
